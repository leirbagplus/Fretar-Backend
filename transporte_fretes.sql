-- PostgreSQL 16/17
--
-- Este script cria o mesmo schema usado pelas migrations do Laravel.
-- Use-o somente em um banco vazio. Nao execute este script e
-- `php artisan migrate` para criar as mesmas tabelas.
--
-- Execute a primeira instrucao conectado ao banco postgres.
CREATE DATABASE transporte_fretes;

-- Depois conecte-se ao banco transporte_fretes antes de executar o restante.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TYPE shipping_status AS ENUM (
    'pending',
    'searching_driver',
    'driver_assigned',
    'in_transit',
    'completed',
    'cancelled'
);

CREATE TYPE shipping_driver_status AS ENUM (
    'pending',
    'accepted',
    'rejected',
    'expired',
    'cancelled'
);

CREATE TYPE payment_status AS ENUM (
    'pending',
    'processing',
    'succeeded',
    'failed',
    'cancelled',
    'refunded'
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email CITEXT NOT NULL,
    password_hash TEXT NOT NULL,
    phone VARCHAR(30),
    address TEXT,
    avatar TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX users_email_unique ON users (email);
CREATE INDEX users_created_at_index ON users (created_at);

CREATE TABLE drivers (
    driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email CITEXT NOT NULL,
    password_hash TEXT NOT NULL,
    phone VARCHAR(30),
    address TEXT,
    cnh VARCHAR(30) NOT NULL,
    status_online BOOLEAN NOT NULL DEFAULT FALSE,
    avatar TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX drivers_email_unique ON drivers (email);
CREATE UNIQUE INDEX drivers_cnh_unique ON drivers (cnh);
CREATE INDEX drivers_status_online_index ON drivers (status_online);

CREATE TABLE vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id BIGINT NOT NULL,
    vehicle_type VARCHAR(50) NOT NULL,
    license_plate VARCHAR(20) NOT NULL,
    capacity_load_kg NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_vehicle_driver
        FOREIGN KEY (driver_id) REFERENCES drivers (driver_id) ON DELETE CASCADE,
    CONSTRAINT chk_vehicle_capacity CHECK (capacity_load_kg > 0),
    CONSTRAINT vehicles_license_plate_unique UNIQUE (license_plate)
);

CREATE INDEX vehicles_driver_id_index ON vehicles (driver_id);

CREATE TABLE shippings (
    shipping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    driver_id BIGINT,
    origin TEXT NOT NULL,
    destination TEXT NOT NULL,
    origin_lat NUMERIC(10, 7),
    origin_lng NUMERIC(10, 7),
    destination_lat NUMERIC(10, 7),
    destination_lng NUMERIC(10, 7),
    about_load TEXT,
    recommended_vehicle VARCHAR(100),
    status shipping_status NOT NULL DEFAULT 'pending',
    value NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    simulacao_iniciada_em TIMESTAMPTZ,
    CONSTRAINT fk_shipping_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_shipping_driver
        FOREIGN KEY (driver_id) REFERENCES drivers (driver_id) ON DELETE SET NULL,
    CONSTRAINT chk_shipping_value CHECK (value > 0),
    CONSTRAINT chk_shipping_origin_lat CHECK (origin_lat BETWEEN -90 AND 90),
    CONSTRAINT chk_shipping_origin_lng CHECK (origin_lng BETWEEN -180 AND 180),
    CONSTRAINT chk_shipping_destination_lat CHECK (destination_lat BETWEEN -90 AND 90),
    CONSTRAINT chk_shipping_destination_lng CHECK (destination_lng BETWEEN -180 AND 180)
);

CREATE INDEX shippings_user_id_index ON shippings (user_id);
CREATE INDEX shippings_driver_id_index ON shippings (driver_id);
CREATE INDEX shippings_status_index ON shippings (status);
CREATE INDEX shippings_created_at_index ON shippings (created_at);

CREATE TABLE payment_methods (
    payment_method_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    stripe_customer_id TEXT NOT NULL,
    stripe_payment_method_id TEXT NOT NULL,
    type VARCHAR(30) NOT NULL,
    last_4_digits CHAR(4),
    card_brand VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_method_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT payment_methods_stripe_payment_method_id_unique
        UNIQUE (stripe_payment_method_id)
);

CREATE INDEX payment_methods_user_id_index ON payment_methods (user_id);
CREATE INDEX payment_methods_stripe_customer_id_index
    ON payment_methods (stripe_customer_id);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipping_id BIGINT NOT NULL,
    payment_method_id BIGINT,
    stripe_payment_intent_id TEXT,
    value NUMERIC(12, 2) NOT NULL,
    payment_status payment_status NOT NULL DEFAULT 'pending',
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_shipping
        FOREIGN KEY (shipping_id) REFERENCES shippings (shipping_id),
    CONSTRAINT fk_payment_method
        FOREIGN KEY (payment_method_id) REFERENCES payment_methods (payment_method_id)
        ON DELETE SET NULL,
    CONSTRAINT chk_payment_value CHECK (value > 0)
);

CREATE UNIQUE INDEX payments_stripe_payment_intent_id_unique
    ON payments (stripe_payment_intent_id);
CREATE INDEX payments_shipping_id_index ON payments (shipping_id);
CREATE INDEX payments_payment_method_id_index ON payments (payment_method_id);
CREATE INDEX payments_payment_status_index ON payments (payment_status);
CREATE INDEX payments_created_at_index ON payments (created_at);

CREATE TABLE shipping_drivers (
    shipping_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    status shipping_driver_status NOT NULL DEFAULT 'pending',
    reply_at TIMESTAMPTZ,
    CONSTRAINT pk_shipping_driver PRIMARY KEY (shipping_id, driver_id),
    CONSTRAINT fk_shipping_driver_shipping
        FOREIGN KEY (shipping_id) REFERENCES shippings (shipping_id) ON DELETE CASCADE,
    CONSTRAINT fk_shipping_driver_driver
        FOREIGN KEY (driver_id) REFERENCES drivers (driver_id) ON DELETE CASCADE
);

CREATE INDEX shipping_drivers_driver_id_index ON shipping_drivers (driver_id);
CREATE INDEX shipping_drivers_status_index ON shipping_drivers (status);

CREATE TABLE evaluations (
    evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    shipping_id BIGINT NOT NULL,
    rating SMALLINT NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evaluation_driver
        FOREIGN KEY (driver_id) REFERENCES drivers (driver_id),
    CONSTRAINT fk_evaluation_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_evaluation_shipping
        FOREIGN KEY (shipping_id) REFERENCES shippings (shipping_id),
    CONSTRAINT evaluations_shipping_id_unique UNIQUE (shipping_id),
    CONSTRAINT chk_evaluation_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX evaluations_driver_id_index ON evaluations (driver_id);
CREATE INDEX evaluations_user_id_index ON evaluations (user_id);

-- Necessaria para os tokens gerados pelo Laravel Sanctum.
CREATE TABLE personal_access_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tokenable_type VARCHAR(255) NOT NULL,
    tokenable_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    token VARCHAR(64) NOT NULL UNIQUE,
    abilities TEXT,
    last_used_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE INDEX personal_access_tokens_tokenable_type_tokenable_id_index
    ON personal_access_tokens (tokenable_type, tokenable_id);
